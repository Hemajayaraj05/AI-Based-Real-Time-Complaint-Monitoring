// Division-specific icon selector
export const getDivisionIcon = (division: string) => {
  const iconMap: Record<string, React.ReactNode> = {
    "cleanliness": <CleanlinessIcon />,
    "water": <WaterIcon />,
    "electricity": <ElectricityIcon />,
    "hostel": <HostelIcon />,
    "transport": <TransportIcon />,
    "library": <LibraryIcon />,
    "food": <FoodIcon />,
    "infrastructure": <InfrastructureIcon />,
    "other": <DocumentIcon />,
  };
  return iconMap[division] || <DocumentIcon />;
};

